export const KNIFE_IDS: KnifeId[] = ['bayonet', 'karambit', 'butterfly'];

export function getStarterPistol(team: Team): SecondaryWeaponId {
  return team === 'defenders' ? 'usps' : 'glock18';
}

export function createWeaponInstance(id: WeaponId): {
  id: WeaponId;
  mag: number;
  reserve: number;
  silenced?: boolean;
  burstMode?: boolean;
} {
  const spec = WEAPONS[id];
  return {
    id,
    mag: spec.magSize,
    reserve: spec.reserveAmmo,
    silenced: spec.hasSilencer ? true : undefined,
    burstMode: spec.hasBurst ? false : undefined,
  };
}
